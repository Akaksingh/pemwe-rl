"""Write paper/table_pilots.tex from the pilot grid CSV (run_scenario_grid.py output).

    python scripts/make_pilot_table.py [--csv results_pilot/grid_round2.csv] [--out paper/table_pilots.tex]

One row per controller, evaluated on the same 293 TRAIN days (in-sample for the learned policies, which
were trained on them; the test split is not used). Reward is recomputed from the logged unweighted
components at w=(1, 0.1, 0.1) with the original scales, so every controller is judged by the same
objective whatever scale it was trained with. The interval is a bootstrap over days for the mean of
the per-day reward difference to the reference; days share weather, so it describes this day set only.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]

NAMES = [  # (controller id, label)
    ("no_threshold", r"Constant action $+1$ (threshold removed)"),
    ("ramp_limited", r"Tuned slew limit"),
    ("naive_as_published", r"Published rule (10\,\% threshold)"),
    ("pilot_utd1_w2-0.1_seed0", r"SAC, $\gamma{=}0.999$, seed 0"),
    ("pilot_utd1_w2-0.1_seed1", r"SAC, $\gamma{=}0.999$, seed 1"),
    ("pilot_utd1_g0.99_seed0", r"SAC, $\gamma{=}0.99$, seed 0"),
    ("pilot2_g0.95_s1", r"SAC, $\gamma{=}0.95$, seed 1"),
    ("pilot_utd1_g0.95_seed0", r"SAC, $\gamma{=}0.95$, seed 0"),
    ("pilot2_g0.95_rs10_s0", r"SAC, $\gamma{=}0.95$, reward$/10$, seed 0"),
    ("pilot2_g0.9_s0", r"SAC, $\gamma{=}0.9$, seed 0"),
    ("pilot2_g0.8_s0", r"SAC, $\gamma{=}0.8$, seed 0"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default=str(ROOT / "results_pilot" / "grid_round2.csv"))
    ap.add_argument("--out", default=str(ROOT / "paper" / "table_pilots.tex"))
    ap.add_argument("--w1", type=float, default=1.0)
    ap.add_argument("--w2", type=float, default=0.1)
    ap.add_argument("--w3", type=float, default=0.1)
    ap.add_argument("--ref", default="no_threshold")
    a = ap.parse_args()

    d = pd.read_csv(a.csv)
    d = d[(d.scenario == "original") & (d.variant == "nominal")].copy()
    d["reward"] = a.w1 * d.r_yield - a.w2 * d.r_deg - a.w3 * d.r_ramp
    ref = d[d.controller == a.ref].set_index("date").reward
    rng = np.random.default_rng(0)

    rows = []
    for cid, label in NAMES:
        g = d[d.controller == cid]
        if g.empty:
            continue
        g = g.set_index("date")
        diff = (g.reward - ref).dropna().to_numpy()
        boots = np.array([rng.choice(diff, len(diff)).mean() for _ in range(4000)])
        lo, hi = np.quantile(boots, [0.025, 0.975])
        better = float((diff > 0).mean() * 100)
        def f0(x):                                   # a real minus sign in LaTeX, not a hyphen
            return f"{x:.0f}".replace("-", "$-$")
        delta = "---" if cid == a.ref else f"{f0(diff.mean())} [{f0(lo)}, {f0(hi)}]"
        rows.append(f"{label} & {g.h2_kg.mean():.1f} & {g.dv_deg_uv.mean():.1f} & {g.n_cycles.mean():.1f} & "
                    f"{delta} \\\\")
    n_days = d[d.controller == a.ref].date.nunique()

    tex = "\n".join([
        r"% GENERATED by scripts/make_pilot_table.py from " + Path(a.csv).name + " -- do not edit by hand.",
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        r"Controller & H$_2$ & $\Delta V$ & trans. & $\Delta$ reward \\",
        r" & [kg/d] & [\si{\micro\volt}/d] & [/d] & vs.\ $+1$ [/d] \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
        r"% days: " + str(n_days),
    ]) + "\n"
    Path(a.out).write_text(tex, encoding="utf-8")
    print(tex)
    print("wrote", a.out)


if __name__ == "__main__":
    main()
